function WorldUIService:Init()
    warn("W1")
    Remotes:CreateToClient("SpawnTextDisplay", {"string", "Vector3", "table?"}, "Unreliable")
end

function WorldUIService:Deferred()

    -- Prepare TextDisplay asset
    for _, Label in Assets.Particles.TextDisplay.Gui.Container:GetChildren() do
        if not Label then continue end
        Label.Visible = false
    end
end

return WorldUIService