-- OmniRal

local SpringLauncher = {}

------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
-- Services
------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

local Debris = game:GetService("Debris")

------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
-- Modules
------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
-- Constants
------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

local CLEAN_TIME = 0.05
local COOLDOWN = 2

------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
-- Remotes
------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
-- Variables
------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

local RNG = Random.new()

------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
-- Private Functions
------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
-- Public API
------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

function SpringLauncher.Setup(Spring: BasePart)
	local Power = Spring:GetAttribute("Power") :: NumberRange
    local Debounce = false

    Spring:SetAttribute("Launched", false)

    Spring.Touched:Connect(function(Hit: BasePart)
        if Debounce then return end
        if not Hit then return end
        if not Hit.Parent then return end
        local Human, Root = Hit.Parent:FindFirstChild("Humanoid") :: Humanoid, Hit.Parent:FindFirstChild("HumanoidRootPart") :: BasePart
        if not Human or not Root then return end
        if Human.Health <= 0 then return end

        local RootAttachment = Root:FindFirstChild("RootAttachment")
        if not RootAttachment then return end

        Debounce = true
        Spring:SetAttribute("Launched", true)

        local LaunchPower = RNG:NextInteger(Power.Min, Power.Max)

        local SpringVelocity = Instance.new("LinearVelocity")
        SpringVelocity.Name = "SpringVelocity"
        SpringVelocity.MaxForce = 1000000
        SpringVelocity.Attachment0 = RootAttachment
        SpringVelocity.VectorVelocity = Spring.CFrame.UpVector * LaunchPower
        SpringVelocity.Parent = Root

        Debris:AddItem(SpringVelocity, CLEAN_TIME)

        task.delay(COOLDOWN, function()
            Spring:SetAttribute("Launched", false)
            Debounce = false
        end)
    end)
end

return SpringLauncher