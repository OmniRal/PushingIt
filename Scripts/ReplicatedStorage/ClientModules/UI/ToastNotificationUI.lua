function ToastNotification.Setup(Gui: ScreenGui)
	if not Gui then return end

	OG_Notification = Gui:FindFirstChild("OG_ToastNotification")
	if not OG_Notification then return end

	OG_Notification.Visible = false
end

return ToastNotification