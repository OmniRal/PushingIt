function BounceUmbrella.Setup(Original: any)
	local Origin = Original.CFrame
    
    local PlayingAnimation = false
	Original:GetAttributeChangedSignal("Launched"):Connect(function()
		if not Original:GetAttribute("Launched") then return end
		if PlayingAnimation then return end

        PlayingAnimation = true
        local GoUp = TweenService:Create(Original, TweenInfo.new(0.1, Enum.EasingStyle.Sine, Enum.EasingDirection.In), {CFrame = Origin * CFrame.new(0, 2, 0)})
        local ComeDown = TweenService:Create(Original, TweenInfo.new(0.5, Enum.EasingStyle.Elastic, Enum.EasingDirection.Out), {CFrame = Origin})

        GoUp.Completed:Connect(function() ComeDown:Play() end)
        ComeDown.Completed:Connect(function() PlayingAnimation = false end)

        GoUp:Play()
	end)
end

return BounceUmbrella