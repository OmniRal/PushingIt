function WindowUpdater.Run()
	for _, Window in CollectionService:GetTagged("DecalWindow") do
		if not Window then continue end

		local FrameStyle, HasCovers = Window:GetAttribute("FrameStyle"), Window:GetAttribute("HasCovers")

		Clean(Window, "Frame")
		Clean(Window, "Covers")

		if FrameStyle ~= nil then NewDecal("Frame", Styles[FrameStyle].Frame, Window.Color, 2, Window) end
		if HasCovers == true then NewDecal("Covers", Styles[FrameStyle].Cover, Window:GetAttribute("CoversColor"), 1, Window) end
	end
end

return WindowUpdater