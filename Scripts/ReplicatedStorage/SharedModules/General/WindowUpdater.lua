local function Clean(Location: Instance, LookFor: string)
	if not Location then return end
	local This = Location:FindFirstChild(LookFor)
	if not This then return end
	This:Destroy()
end

local function NewDecal(Name: string, ID: number, Color: Color3, ZIndex: number, Parent: BasePart)
	local Decal = Instance.new("Decal")
	Decal.Name = Name
	Decal.Face = Enum.NormalId.Front
	Decal.Texture = "rbxassetid://" .. ID
	Decal.Color3 = Color
	Decal.ZIndex = ZIndex
	Decal.Parent = Parent
end

