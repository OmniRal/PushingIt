-- Takes a folder that has int values and converts them into an option table used for RollPick
function Roll.ConvertFolderToOptions(Folder: Folder)
    if not Folder then return end

    local Options: {{Choice: string, Chance: number}} = {}
    for _, Val in Folder:GetChildren() do
        if not Val:IsA("IntValue") then continue end
        if Val.Value <= 0 then continue end
        table.insert(Options, {Choice = Val.Name, Chance = Val.Value})
    end

    return Options
end

-- Randomly picks an option from a table of choices
function Roll.Pick(Options: {{Choice: any, Chance: number}}): any?
    if #Options <= 0 then return end
    if #Options == 1 then
        return Options[1].Choice
    end 

    local TotalWeight = 0
    for _, Info in Options do
        TotalWeight += Info.Chance
    end

    local ThisRoll = RNG:NextNumber(0, TotalWeight)
    local Sum = 0
    local ChanceNeeded = 0
    local AvailablePicks: {number} = {}

    for Num, Info in ipairs(Options) do
        Sum += Info.Chance
        if ThisRoll <= Sum then
            ChanceNeeded = Info.Chance
            table.insert(AvailablePicks, Num)
            break
        end
    end

    for Num, Info in ipairs(Options) do
        if math.abs(Info.Chance - ChanceNeeded) > 0.01 then continue end
        if table.find(AvailablePicks, Num) then continue end
        table.insert(AvailablePicks, Num)
    end

    local Picked = Options[AvailablePicks[RNG:NextInteger(1, #AvailablePicks)]].Choice

    return Picked
end

return Roll